// Divide um item em frases (para a tradução por toque). Respeita 「…」 e gruda frases muito curtas (はい。) na seguinte.
function splitSentences(s){
  var out=[],cur="",depth=0,i,ch;
  for(i=0;i<s.length;i++){
    ch=s.charAt(i);cur+=ch;
    if(ch==="「")depth++;
    else if(ch==="」"&&depth>0)depth--;
    else if(depth===0&&(ch==="。"||ch==="！"||ch==="？")){
      // fecha aspas/espacos colados logo depois
      while(i+1<s.length&&/[」』）\s]/.test(s.charAt(i+1))&&s.charAt(i+1)!=="「"){cur+=s.charAt(++i)}
      out.push(cur.trim());cur="";
    }
  }
  if(cur.trim())out.push(cur.trim());
  // frases curtinhas (はい。 いいね。) grudam na seguinte, para nao virarem alvos minusculos de toque
  var res=[],pend="";
  out.forEach(function(x,k){
    var base=x.replace(/\{([^|}]+)\|[^}]+\}/g,"$1").replace(/\s/g,"");
    if(!pend&&base.length<=6&&k<out.length-1){pend=x;return}
    res.push(pend?pend+x:x);pend="";
  });
  if(pend)res.push(pend);
  return res;
}
